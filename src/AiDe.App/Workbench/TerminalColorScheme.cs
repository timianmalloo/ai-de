using System.Windows.Media;

namespace AiDe.App.Workbench;

/// <summary>
/// A named terminal colour scheme: the sixteen ANSI colours plus background, foreground and cursor.
/// Chosen per session so a user can tell two terminals apart by how their content reads, not only by
/// the tab caption. The ANSI sixteen are a vocabulary programs address by index (see
/// <see cref="TerminalPalette"/>), so a scheme re-maps the vocabulary — it never renames it.
/// </summary>
public sealed record TerminalColorScheme(
    string Name,
    Color Background,
    Color Foreground,
    Color Cursor,
    Color Accent,
    IReadOnlyList<Color> Ansi16)
{
    private static Color C(byte r, byte g, byte b) => Color.FromRgb(r, g, b);

    /// <summary>The shipped default — matches the App.xaml <c>TerminalAnsi*</c> tokens.</summary>
    public static TerminalColorScheme Default { get; } = new(
        "Default",
        C(0x0D, 0x10, 0x14), C(0xE4, 0xE9, 0xEF), C(0x5B, 0x9D, 0xD9), C(0x5B, 0x9D, 0xD9),
        [
            C(0x1A, 0x1F, 0x26), C(0xE0, 0x7A, 0x6F), C(0x5F, 0xB9, 0x8F), C(0xD8, 0xA6, 0x50),
            C(0x5B, 0x9D, 0xD9), C(0xB0, 0x8A, 0xD0), C(0x5F, 0xB2, 0xB9), C(0xC3, 0xCB, 0xD6),
            C(0x5A, 0x64, 0x72), C(0xF0, 0x9A, 0x90), C(0x84, 0xD2, 0xAC), C(0xEF, 0xC2, 0x75),
            C(0x8F, 0xC0, 0xEA), C(0xCB, 0xA9, 0xE4), C(0x88, 0xCD, 0xD3), C(0xF2, 0xF6, 0xFA),
        ]);

    /// <summary>A warm amber-leaning scheme.</summary>
    public static TerminalColorScheme Warm { get; } = new(
        "Warm",
        C(0x1A, 0x14, 0x10), C(0xF0, 0xE6, 0xD8), C(0xE0, 0x9A, 0x50), C(0xE0, 0x9A, 0x50),
        [
            C(0x2A, 0x20, 0x18), C(0xE0, 0x6A, 0x54), C(0x8C, 0xB0, 0x5A), C(0xE0, 0xA8, 0x4E),
            C(0xD8, 0x92, 0x5A), C(0xCE, 0x8A, 0x86), C(0xC9, 0xB0, 0x6A), C(0xEC, 0xDD, 0xC8),
            C(0x6A, 0x5A, 0x48), C(0xF0, 0x8A, 0x70), C(0xC8, 0xD2, 0x84), C(0xF2, 0xC6, 0x78),
            C(0xEC, 0xB0, 0x7C), C(0xE0, 0xB0, 0xA0), C(0xDE, 0xCE, 0x8E), C(0xFB, 0xF4, 0xE8),
        ]);

    /// <summary>A cool teal/blue-leaning scheme.</summary>
    public static TerminalColorScheme Cool { get; } = new(
        "Cool",
        C(0x0B, 0x14, 0x1C), C(0xDA, 0xE6, 0xF0), C(0x54, 0xC0, 0xD0), C(0x54, 0xC0, 0xD0),
        [
            C(0x14, 0x20, 0x2A), C(0xE0, 0x7A, 0x8A), C(0x5F, 0xC0, 0x9A), C(0x6E, 0xB0, 0xC8),
            C(0x54, 0xA6, 0xE0), C(0x9A, 0x9A, 0xE0), C(0x54, 0xC0, 0xD0), C(0xC0, 0xCE, 0xDA),
            C(0x48, 0x5A, 0x6A), C(0x90, 0xC6, 0xE8), C(0x84, 0xDC, 0xB6), C(0x9A, 0xD0, 0xE4),
            C(0x8F, 0xC6, 0xEA), C(0xB4, 0xB4, 0xEE), C(0x88, 0xD8, 0xE4), C(0xEC, 0xF4, 0xFA),
        ]);

    /// <summary>Maximum legibility: pure black ground, bright ink and brights.</summary>
    public static TerminalColorScheme HighContrast { get; } = new(
        "High-contrast",
        C(0x00, 0x00, 0x00), C(0xFF, 0xFF, 0xFF), C(0x8F, 0xC0, 0xEA), C(0x8F, 0xC0, 0xEA),
        [
            C(0x00, 0x00, 0x00), C(0xFF, 0x6B, 0x6B), C(0x5A, 0xF0, 0xA0), C(0xFF, 0xD8, 0x6B),
            C(0x8F, 0xC0, 0xEA), C(0xD8, 0xA8, 0xF0), C(0x6B, 0xE8, 0xF0), C(0xFF, 0xFF, 0xFF),
            C(0x9A, 0xA4, 0xB0), C(0xFF, 0x8A, 0x8A), C(0x84, 0xFF, 0xC0), C(0xFF, 0xE8, 0x90),
            C(0xB0, 0xDC, 0xFF), C(0xE8, 0xC0, 0xFF), C(0x90, 0xF4, 0xFF), C(0xFF, 0xFF, 0xFF),
        ]);

    /// <summary>The presets offered in the colour-scheme menu, in order.</summary>
    public static IReadOnlyList<TerminalColorScheme> Presets { get; } =
        [Default, Warm, Cool, HighContrast];
}

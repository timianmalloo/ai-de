"""Per-test failure rates over loadflake-runs/*.trx -> rates.md (stdlib only)."""
import glob
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.normpath(os.path.join(ROOT, "..", "..", "..", "..", "loadflake-runs"))
OUT = os.path.join(ROOT, "rates.md")


def local(tag):
    return tag.rsplit("}", 1)[-1]


def parse(path):
    tree = ET.parse(path)
    names = {}
    results = []
    for el in tree.iter():
        t = local(el.tag)
        if t == "UnitTest":
            for c in el.iter():
                if local(c.tag) == "TestMethod":
                    names[el.get("id")] = c.get("className", "") + "." + c.get("name", "")
        elif t == "UnitTestResult":
            msg = ""
            for c in el.iter():
                if local(c.tag) == "Message":
                    msg = (c.text or "").strip().splitlines()[0] if (c.text or "").strip() else ""
                    break
            results.append((el.get("testId"), el.get("testName"), el.get("outcome"), msg))
    return names, results


def main():
    totals = {}
    runs_by_suite = {}
    fails = {}
    for path in sorted(glob.glob(os.path.join(RUNS, "*.trx"))):
        m = re.match(r"(core|app)-(\d+)\.trx$", os.path.basename(path))
        if not m:
            continue
        suite, k = m.group(1), int(m.group(2))
        names, results = parse(path)
        runs_by_suite.setdefault(suite, set()).add(k)
        totals[suite] = max(totals.get(suite, 0), len(results))
        for tid, tname, outcome, msg in results:
            if outcome == "Failed":
                full = names.get(tid, tname)
                d = fails.setdefault((suite, full), {"runs": set(), "msgs": []})
                d["runs"].add(k)
                if msg not in d["msgs"]:
                    d["msgs"].append(msg)
    lines = [
        "---",
        "id: proof-wl-loadflake-rates",
        'title: "Evidence: T31 per-test failure rates over N full runs"',
        "type: proof-pack",
        "status: draft",
        'owner: "@timianmalloo"',
        'phase: "workbench-loops"',
        "links:",
        "  - { to: architecture, rel: implements }",
        'review-by: "2026-11-19"',
        "summary: >-",
        "  Per-test failure counts from the loadflake full Core+App runs, generated by rates.py from the trx files.",
        "---",
        "",
        "# Per-test failure rates",
        "",
    ]
    for suite in sorted(runs_by_suite):
        lines.append("- %s: %d results per run, N = %d runs (%s)" % (
            suite, totals[suite], len(runs_by_suite[suite]), sorted(runs_by_suite[suite])))
    lines += ["", "| Suite | Test | Failures/runs | Runs | First line of each distinct message |", "|---|---|---|---|---|"]
    for (suite, full), d in sorted(fails.items()):
        n = len(runs_by_suite[suite])
        msgs = " ; ".join(x.replace("|", "/") for x in d["msgs"])
        lines.append("| %s | %s | %d/%d | %s | %s |" % (suite, full, len(d["runs"]), n, sorted(d["runs"]), msgs))
    if not fails:
        lines.append("| - | no test failed in any run | 0 | - | - |")
    alone = {}
    apath = os.path.join(ROOT, "alone.txt")
    if os.path.exists(apath):
        with open(apath, encoding="utf-8", errors="replace") as f:
            for ln in f:
                m = re.match(r"(\S+) alone failures (\d+)/10", ln)
                if m:
                    alone[m.group(1)] = int(m.group(2))
    if alone:
        lines += ["", "## Alone (10 runs each, --filter FullyQualifiedName~method) and class", "",
                  "| Test method | In suite | Alone | Class |", "|---|---|---|---|"]
        for (suite, full), d in sorted(fails.items()):
            meth = full.rsplit(".", 1)[-1]
            a = next((v for k, v in alone.items() if k == meth), None)
            n = len(runs_by_suite[suite])
            if a is None:
                cls = "not run alone"
            elif a == 0:
                cls = "load-only"
            elif a == 10:
                cls = "fails-alone"
            else:
                cls = "intermittent"
            lines.append("| %s | %d/%d | %s/10 | %s |" % (meth, len(d["runs"]), n, a, cls))
    with open(OUT, "w", encoding="utf-8", errors="replace") as f:
        f.write("\n".join(lines) + "\n")


main()

#!/usr/bin/env python3
"""Spike: native harness presence, version and documented headless entry on THIS machine.

Read-only. Runs `<cli> --version` and `<cli> --help` for each of the six harness families the
workbench-loops spec names (AC-H01a), and looks for the documented headless/login tokens in the
installed build's own help text. No login, no model call, no credential read.

Oracle discipline (SRE review, 2026-10-18):
- tokens match on word boundaries, so `-p` does not match `--print` and `exec` does not match
  "execute";
- exit codes are recorded, never discarded;
- the version is the first `\\d+.\\d+.\\d+` in stdout (stderr banners, e.g. a self-update notice,
  cannot become the version);
- the generated table is written to RESULT.generated.md; RESULT.md is hand-written and includes
  it, so a re-run never deletes the follow-up notes.

PATH is the invoking shell's PATH, not the WPF app's — a known limit, stated in the result.
"""
from __future__ import annotations

import datetime as dt
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
VERSION_RE = re.compile(r"\d+\.\d+\.\d+")

# (family, cli, help args, [documented tokens to look for])
PROBES = [
    ("Anthropic / Claude Code", "claude", ["--help"], ["-p", "--output-format", "stream-json", "setup-token"]),
    ("OpenAI / Codex", "codex", ["--help"], ["exec", "app-server", "login"]),
    ("GitHub Copilot CLI", "copilot", ["--help"], ["--acp", "-p", "--allow-tool", "login"]),
    ("xAI / Grok Build", "grok", ["--help"], ["agent", "stdio", "login", "--prompt"]),
    ("Google / Antigravity", "agy", ["--help"], ["--output-format", "stream-json", "login", "headless"]),
    ("Meta / Muse Code", "muse", ["--help"], ["exec", "--json", "login", "serve"]),
]


def run(cmd: list[str], timeout: int = 60) -> tuple[int | None, str, str]:
    """Run a CLI through the shell shim on Windows; return (exit, stdout, stderr)."""
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                              shell=(sys.platform == "win32"), encoding="utf-8", errors="replace")
        return proc.returncode, proc.stdout or "", proc.stderr or ""
    except subprocess.TimeoutExpired:
        return None, "", "TIMEOUT"
    except OSError as exc:  # not found / not executable
        return None, "", f"OSERROR {exc}"


def has_token(text: str, token: str) -> bool:
    return re.search(r"(?<![\w-])" + re.escape(token) + r"(?![\w-])", text) is not None


def main() -> int:
    lines = ["<!-- generated by probe.py; do not edit — RESULT.md includes this file -->", "",
             f"Run: {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')} · "
             f"host: {sys.platform} · python {sys.version.split()[0]} · PATH = the invoking shell's", "",
             "| Family | CLI resolved | Version (stdout regex) | exit (version / help) | Tokens found in --help | Not found |",
             "|---|---|---|---|---|---|"]
    for family, cli, hargs, tokens in PROBES:
        path = shutil.which(cli)
        if not path:
            lines.append(f"| {family} | NOT FOUND | — | — | — | all |")
            continue
        vexit, vout, _ = run([cli, "--version"])
        m = VERSION_RE.search(vout)
        version = m.group(0) if m else "not parsed"
        hexit, hout, herr = run([cli, *hargs])
        htext = hout + herr
        found = [t for t in tokens if has_token(htext, t)]
        missing = [t for t in tokens if not has_token(htext, t)]
        lines.append(f"| {family} | `{path}` | `{version}` | {vexit} / {hexit} | "
                     f"{', '.join(f'`{t}`' for t in found) or 'none'} | "
                     f"{', '.join(f'`{t}`' for t in missing) or 'none'} |")
    (HERE / "RESULT.generated.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
